const DICTS: Record<Locale, Dict> = { he, en };

export function t(key: string, locale: Locale = DEFAULT_LOCALE, params?: Record<string, string | number>): string {
  const template = DICTS[locale][key] ?? DICTS[DEFAULT_LOCALE][key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce((acc, [name, value]) => acc.replaceAll(`{${name}}`, String(value)), template);
}
